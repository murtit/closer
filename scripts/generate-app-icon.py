#!/usr/bin/env python3
"""Generates the Closer app icon from its geometry: SVG sources and the PNGs of the asset catalog.

Usage:
  scripts/generate-app-icon.py           # writes design/app-icon/*.svg and the AppIcon PNGs
  scripts/generate-app-icon.py --check   # exits with 1 if the committed files are out of date

The icon is two equally sized, slightly overlapping circles on a solid pine background:
coral on the left, cream on the right, and a 50/50 mix of both where they overlap. All
values below are the single source of truth; the PNGs are rendered from them (no external
renderer needed) at 1024 x 1024, opaque RGB without corners, as Apple requires. The same
proportions are used by `CloserMarkView` in the app.

Variants of the asset catalog:
  icon_light.png   default icon
  icon_dark.png    identical, the background is already dark
  icon_tinted.png  grayscale on black, iOS tints it with the user's colour
"""
import math
import os
import struct
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONSET = os.path.join(ROOT, "Closer", "Resources", "Assets.xcassets", "AppIcon.appiconset")
DESIGN = os.path.join(ROOT, "design", "app-icon")

SIZE = 1024
RADIUS = 224      # each circle is 448 px wide
OFFSET = 160      # centre distance from the middle; overlap = 2 * (RADIUS - OFFSET) = 128 px
# Outer bounds: 128 px margin to the left and right edge (1/8 of the canvas), 288 px top and bottom.

COLORS = {
    "light": {"background": 0x10231F, "left": 0xF5A58C, "right": 0xF8F3E9, "overlap": 0xF6CCBA},
    "tinted": {"background": 0x000000, "left": 0xB4B4B4, "right": 0xF3F3F3, "overlap": 0xD4D4D4},
}
VARIANTS = {"icon_light.png": "light", "icon_dark.png": "light", "icon_tinted.png": "tinted"}
SVGS = {"closer-app-icon.svg": "light", "closer-app-icon-tinted.svg": "tinted"}


def rgb(value: int) -> tuple:
    return (value >> 16) & 0xFF, (value >> 8) & 0xFF, value & 0xFF


def svg(palette: dict) -> str:
    c = SIZE / 2
    left, right = c - OFFSET, c + OFFSET
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
  <!-- Generated by scripts/generate-app-icon.py, do not edit by hand. -->
  <defs>
    <clipPath id="left">
      <circle cx="{left:g}" cy="{c:g}" r="{RADIUS}"/>
    </clipPath>
  </defs>
  <rect width="{SIZE}" height="{SIZE}" fill="#{palette['background']:06X}"/>
  <circle cx="{left:g}" cy="{c:g}" r="{RADIUS}" fill="#{palette['left']:06X}"/>
  <circle cx="{right:g}" cy="{c:g}" r="{RADIUS}" fill="#{palette['right']:06X}"/>
  <circle cx="{right:g}" cy="{c:g}" r="{RADIUS}" fill="#{palette['overlap']:06X}" clip-path="url(#left)"/>
</svg>
"""


def coverage(x: float, y: float, cx: float, cy: float) -> float:
    """Share of the pixel centred at (x, y) inside the circle, from its signed distance."""
    distance = math.hypot(x - cx, y - cy) - RADIUS
    return min(1.0, max(0.0, 0.5 - distance))


def render(palette: dict) -> bytes:
    """Raw 8-bit RGB rows, each prefixed with PNG filter type 0."""
    background, left, right, overlap = (rgb(palette[k]) for k in ("background", "left", "right", "overlap"))
    c = SIZE / 2
    rows = bytearray()
    for py in range(SIZE):
        rows.append(0)
        y = py + 0.5
        for px in range(SIZE):
            x = px + 0.5
            a = coverage(x, y, c - OFFSET, c)
            b = coverage(x, y, c + OFFSET, c)
            for i in range(3):
                under = background[i] + (left[i] - background[i]) * a
                top = right[i] + (overlap[i] - right[i]) * a
                rows.append(round(under + (top - under) * b))
    return bytes(rows)


def png(raw: bytes) -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    header = struct.pack(">IIBBBBB", SIZE, SIZE, 8, 2, 0, 0, 0)  # 8-bit RGB, no alpha
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def decode(data: bytes):
    """Pixel rows of a PNG written by `png`, or None if it has another format."""
    if not data.startswith(b"\x89PNG\r\n\x1a\n"):
        return None
    pos, header, idat = 8, None, b""
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        if kind == b"IHDR":
            header = body
        elif kind == b"IDAT":
            idat += body
        pos += 12 + length
    if header != struct.pack(">IIBBBBB", SIZE, SIZE, 8, 2, 0, 0, 0):
        return None
    return zlib.decompress(idat)


def main() -> int:
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] and not check:
        print(__doc__, file=sys.stderr)
        return 2

    rendered = {name: render(palette) for name, palette in COLORS.items()}
    stale = []
    os.makedirs(DESIGN, exist_ok=True)

    for filename, name in SVGS.items():
        path = os.path.join(DESIGN, filename)
        content = svg(COLORS[name])
        if check:
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != content:
                stale.append(path)
        else:
            with open(path, "w", encoding="utf-8") as file:
                file.write(content)

    for filename, name in VARIANTS.items():
        path = os.path.join(ICONSET, filename)
        if check:
            if not os.path.exists(path) or decode(open(path, "rb").read()) != rendered[name]:
                stale.append(path)
        else:
            with open(path, "wb") as file:
                file.write(png(rendered[name]))

    if stale:
        print("App icon out of date, run scripts/generate-app-icon.py:", *stale, sep="\n  ")
        return 1
    print("App icon up to date" if check else f"Wrote {len(SVGS)} SVGs and {len(VARIANTS)} PNGs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
